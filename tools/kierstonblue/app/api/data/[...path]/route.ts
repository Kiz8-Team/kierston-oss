import { createHash } from "node:crypto";
import { createReadStream } from "node:fs";
import { stat } from "node:fs/promises";
import { Readable } from "node:stream";
import type { ReadableStream as WebReadableStream } from "node:stream/web";
import { resolveDataset } from "@/lib/server/repo";

/**
 * Stream a dataset out of kierston/ — /api/data/sim/pois.json,
 * /api/data/sim/population.bin, and so on.
 *
 * Streaming rather than reading matters here: population.bin is 6 MB and
 * buildings.json is 17 MB, and neither should sit in the server's heap once a
 * response has been written.
 *
 * Ranges, and what they are for
 * -----------------------------
 * A container file holds many sections and a reader wants one of them. The
 * whole of sim_data is around 160 MB, and the page showing somebody's firearms
 * has no use for 147,301 civil dockets — which is why pack_records.py writes
 * six files rather than one. A section directory plus `Range` is the same
 * bargain without the file count: read the header, then ask for the bytes the
 * section occupies.
 *
 * Only a single range is honoured. Multipart ranges mean a `multipart/
 * byteranges` body, and nothing here asks for two disjoint sections at once —
 * a reader that wanted two would issue two requests, which costs a round trip
 * and saves a parser. A request for more than one range is answered with the
 * whole file, which the RFC allows and which cannot corrupt a reader that was
 * expecting less.
 */

const TYPES: Record<string, string> = {
  json: "application/json",
  bin: "application/octet-stream",
  graphml: "application/xml",
  xml: "application/xml",
  csv: "text/csv",
};

interface Span {
  start: number;
  end: number;
}

/**
 * Parse a single byte range against a known size.
 *
 * Returns null where the header is absent or asks for something this route
 * does not serve, and "unsatisfiable" where it is well formed but off the end
 * of the file — the two are different answers, 200 and 416, and collapsing
 * them would hand a reader an entire population when it asked for eight bytes
 * that do not exist.
 */
function parseRange(header: string | null, size: number): Span | "unsatisfiable" | null {
  if (!header) return null;
  const match = /^bytes=(\d*)-(\d*)$/.exec(header.trim());
  if (!match) return null;

  const [, from, to] = match;
  if (!from && !to) return null;

  // `bytes=-500` is the last 500 bytes, not a range starting at zero. The
  // directory of a container is at the front, so nothing here uses it; it is
  // handled because getting it silently wrong would serve the wrong bytes
  // under a 206 that claims they are the right ones.
  let start = from ? Number(from) : Math.max(0, size - Number(to));
  let end = from ? (to ? Number(to) : size - 1) : size - 1;

  if (!Number.isFinite(start) || !Number.isFinite(end)) return null;
  if (start >= size) return "unsatisfiable";
  if (end >= size) end = size - 1;
  if (end < start) return "unsatisfiable";

  return { start, end };
}

export async function GET(
  request: Request,
  { params }: { params: Promise<{ path: string[] }> },
) {
  const { path } = await params;
  const target = await resolveDataset(path);
  if (!target) {
    return Response.json({ error: "unknown dataset" }, { status: 404 });
  }

  let size: number;
  let mtime: number;
  try {
    const info = await stat(target);
    if (!info.isFile()) throw new Error("not a file");
    size = info.size;
    mtime = info.mtimeMs;
  } catch {
    return Response.json(
      { error: `no such dataset: ${path.join("/")}` },
      { status: 404 },
    );
  }

  const extension = target.split(".").pop() ?? "";
  // The path is in the tag because the same URL serves a different file for
  // each city build, and two builds can share a size and a timestamp.
  const etag = `"${createHash("sha1").update(target).digest("hex").slice(0, 8)}-${size.toString(16)}-${Math.round(mtime).toString(16)}"`;
  const headers: Record<string, string> = {
    "Content-Type": TYPES[extension] ?? "application/octet-stream",
    // Datasets are regenerated by hand, so revalidation is cheap insurance
    // against a stale copy surviving a rebuild of the population.
    "Cache-Control": "no-cache",
    ETag: etag,
    // Announced on every response, not only the partial ones: a reader decides
    // whether to ask for a section or the whole file from what the first
    // response said, and the first response is usually a full one.
    "Accept-Ranges": "bytes",
  };

  const span = parseRange(request.headers.get("range"), size);
  if (span === "unsatisfiable") {
    return new Response(null, {
      status: 416,
      headers: { ...headers, "Content-Range": `bytes */${size}` },
    });
  }

  const stream = Readable.toWeb(
    span ? createReadStream(target, { start: span.start, end: span.end })
         : createReadStream(target),
  ) as WebReadableStream<Uint8Array>;

  if (!span) {
    return new Response(stream as unknown as BodyInit, {
      headers: { ...headers, "Content-Length": String(size) },
    });
  }

  return new Response(stream as unknown as BodyInit, {
    status: 206,
    headers: {
      ...headers,
      // `end` is inclusive in both the header and createReadStream, which is
      // the one place the two conventions agree and the reason the span is
      // carried inclusive rather than as a half-open pair.
      "Content-Length": String(span.end - span.start + 1),
      "Content-Range": `bytes ${span.start}-${span.end}/${size}`,
    },
  });
}
