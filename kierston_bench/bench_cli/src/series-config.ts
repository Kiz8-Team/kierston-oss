/**
 * The prep config the New series page writes. Technical families read the
 * chosen days as they are; an RTI or DT family reads a staged incident, so
 * choosing one also writes a `[[scenarios]]` entry for every catalogued
 * scenario that feeds it.
 */

import { BENCH_SCENARIOS } from "../../../kierston_scenarios/scenarios/catalog.ts";
import { GENERATORS, STAGED_GENERATORS } from "../../task_generators/src/index.ts";

const STAGED = new Set(STAGED_GENERATORS.map((generator) => generator.family));
const SCENARIO_FAMILIES = new Set(BENCH_SCENARIOS.flatMap((scenario) => scenario.families));

/** Every family the builder can offer, in group order: a staged family only when some scenario stages it. */
export const SERIES_FAMILIES = GENERATORS.map((generator) => generator.family).filter(
  (family) => !STAGED.has(family) || SCENARIO_FAMILIES.has(family),
);

export function isStagedFamily(family: string): boolean {
  return STAGED.has(family);
}

export interface SeriesChoice {
  id: string;
  seed: number;
  days: readonly string[];
  families: ReadonlySet<string>;
  copies: number;
  attempts: number;
}

/** The scenarios a choice of families needs staged, in catalogue order. */
export function scenariosFor(families: ReadonlySet<string>): string[] {
  return BENCH_SCENARIOS.filter((scenario) => scenario.families.some((family) => families.has(family))).map((scenario) => scenario.id);
}

/** First line of a config the New series form wrote; deleting its series deletes it too. */
export const GENERATED_HEADER = "# Generated by the Kierston Bench TUI.";

export function seriesToml(choice: SeriesChoice): string {
  const families = SERIES_FAMILIES.filter((family) => choice.families.has(family));
  const include = families.length === SERIES_FAMILIES.length ? '"all"' : `[${families.map((family) => JSON.stringify(family)).join(", ")}]`;
  const lines = [
    GENERATED_HEADER,
    "[series]",
    `id = ${JSON.stringify(choice.id)}`,
    `seed = ${choice.seed}`,
    `days = [${choice.days.map((day) => JSON.stringify(day)).join(", ")}]`,
    "",
    "[tasks]",
    `include = ${include}`,
    "exclude = []",
    `copies = ${choice.copies}`,
    `attempts_per_copy = ${choice.attempts}`,
    "",
  ];
  // No `count`: `copies` sets how many deltas each scenario gets per day.
  for (const scenario of scenariosFor(choice.families)) {
    lines.push("[[scenarios]]", `id = ${JSON.stringify(scenario)}`, "");
  }
  return lines.join("\n");
}
