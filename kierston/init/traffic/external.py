"""Build the persistent vehicles that repeatedly enter Kierston from outside.

The people behind these vehicles are deliberately not residents.  What persists
is only what a road sensor can encounter again: a vehicle, its registration,
its usual destination and the broad rhythm of its visits.  One-off visitors and
through traffic are date-local and are generated by the day exporter instead.
"""

import argparse
import json
import math
import random
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import jurisdiction as legal  # noqa: E402
import profile as city_profile  # noqa: E402
from paths import POIS, SIM_DATA  # noqa: E402
from personal_records.registries import REFERENCE_YEAR  # noqa: E402


POPULATION = SIM_DATA / "population.json"
VEHICLES = SIM_DATA / "vehicles.json"
WORKPLACES = SIM_DATA / "workplaces.json"
RULES = Path(__file__).with_name("us_plate_rules.json")
TRAFFIC = legal.state_module("traffic")
OUTPUT = SIM_DATA / "external_traffic.json"
DEFAULT_SEED = 20260728

LETTERS = "ABCDEFGHJKLMNPRSTUVWXYZ"
DIGITS = "0123456789"

TRUCKS = [
    ("Freightliner", "Cascadia", "tractor"),
    ("International", "LT", "tractor"),
    ("Volvo", "VNL", "tractor"),
    ("Kenworth", "T680", "tractor"),
    ("Peterbilt", "579", "tractor"),
    ("Freightliner", "M2", "truck"),
    ("International", "MV", "truck"),
    ("Isuzu", "N-Series", "truck"),
]


def clamp(value, low, high):
    return max(low, min(high, value))


def plate(pattern, rng):
    return "".join(rng.choice(LETTERS) if char == "L"
                   else rng.choice(DIGITS) if char == "D"
                   else char for char in pattern)


def choose_rule(rules, kind, rng):
    """Jurisdiction mix for repeat visitors, from the state's weights."""
    fallback = {
        "worker": (60.0, 1.0, 0.18, 0.025),
        "delivery": (45.0, 1.4, 0.38, 0.10),
        "repeat_visitor": (54.0, 1.1, 0.24, 0.04),
    }[kind]
    regional = TRAFFIC.RECURRING_WEIGHTS[kind]
    weights = [regional.get(row["code"], fallback[row["tier"]]) for row in rules]
    return rng.choices(rules, weights=weights)[0]


def vehicle_market(registry, rng, limit=512):
    rows = [row for row in registry["vehicles"].values()
            if row.get("body") in ("car", "suv", "pickup", "van")]
    sample = rng.sample(rows, min(limit, len(rows)))
    return [{
        "make": row["make"], "model": row["model"], "body": row["body"],
        "colour": row["colour"], "model_year": row["model_year"],
    } for row in sample]


def destinations(workplaces, pois):
    """A bounded set of route anchors shared by thousands of external tours."""
    work = sorted(workplaces["site_records"],
                  key=lambda row: -max(1, row.get("capacity", 1)))[:256]
    result = [{
        "id": f"work/{index}", "source": row["id"],
        "label": row.get("name") or row.get("address") or "Workplace",
        "lat": row["lat"], "lon": row["lon"], "kind": "work",
        "weight": max(1, row.get("capacity", 1)),
    } for index, row in enumerate(work)]

    allowed = {"food", "retail", "services", "health", "lodging", "leisure"}
    groups = [group["id"] for group in pois["groups"]]
    seen = set()
    candidates = []
    for index, point in enumerate(pois["points"]):
        group = groups[point[2]]
        if group not in allowed:
            continue
        # Dense OSM catalogues commonly repeat a POI at the building and node.
        key = (round(point[0], 5), round(point[1], 5), point[4] or "")
        if key in seen:
            continue
        seen.add(key)
        candidates.append({
            "id": f"visit/{index}", "source": None,
            "label": point[4] or group.title(), "lat": point[0], "lon": point[1],
            "kind": group, "weight": 3 if group in ("retail", "food") else 1,
        })
    # Stable, broad coverage rather than thousands of almost-identical routes.
    result.extend(candidates[:384])
    return result


def make_vehicle(index, kind, destination, market, rules, used, rng):
    rule = choose_rule(rules, kind, rng)
    while True:
        text = plate(rng.choice(rule["patterns"]), rng)
        key = (rule["code"], text)
        if key not in used:
            used.add(key)
            break

    if kind == "delivery" and rng.random() < 0.58:
        make, model, body = rng.choice(TRUCKS)
        model_year = rng.randint(2014, REFERENCE_YEAR)
        colour = rng.choices(
            ["white", "black", "silver", "red", "blue"],
            weights=[62, 12, 11, 8, 7], k=1)[0]
    else:
        specimen = rng.choice(market)
        make, model, body = specimen["make"], specimen["model"], specimen["body"]
        model_year, colour = specimen["model_year"], specimen["colour"]

    bearing = rule["bearing"]
    if bearing is None:
        bearing = rng.uniform(0, 360)
    else:
        bearing = (bearing + rng.gauss(0, 18)) % 360

    if kind == "worker":
        arrival = round(clamp(rng.gauss(8 * 60 + 10, 65), 5 * 60, 12 * 60))
        dwell = round(clamp(rng.gauss(8 * 60 + 35, 75), 4 * 60, 13 * 60))
        weekdays = [0, 1, 2, 3, 4]
        frequency = rng.uniform(0.78, 0.98)
    elif kind == "delivery":
        arrival = round(clamp(rng.gauss(9 * 60, 150), 3 * 60, 17 * 60))
        dwell = round(clamp(rng.gauss(75, 35), 20, 240))
        weekdays = [0, 1, 2, 3, 4, 5]
        frequency = rng.uniform(0.45, 0.90)
    else:
        arrival = round(clamp(rng.gauss(14 * 60, 210), 7 * 60, 22 * 60))
        dwell = round(clamp(rng.gauss(125, 75), 25, 8 * 60))
        weekdays = list(range(7))
        frequency = rng.uniform(0.08, 0.32)

    return {
        "id": f"EXT-R-{index:06d}", "kind": kind,
        "state": rule["code"], "plate": text,
        "plate_sides": ["front", "rear"] if rule["front"] else ["rear"],
        "make": make, "model": model, "body": body, "colour": colour,
        "model_year": model_year,
        "home_bearing": round(bearing, 2), "destination": destination,
        "arrival_minute": arrival, "dwell_minutes": dwell,
        "weekdays": weekdays, "frequency": round(frequency, 5),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--out", type=Path, default=OUTPUT)
    args = parser.parse_args()

    for path in (POPULATION, VEHICLES, WORKPLACES, POIS, RULES):
        if not path.exists():
            raise SystemExit(f"{path.name} is missing — run the earlier stages first")

    rng = random.Random(args.seed ^ 0x45585452)
    population = json.loads(POPULATION.read_text())
    registry = json.loads(VEHICLES.read_text())
    workplaces = json.loads(WORKPLACES.read_text())
    pois = json.loads(POIS.read_text())
    rule_file = json.loads(RULES.read_text())
    # Patterns are national; tier and bearing come from the state the city is in.
    rules = [dict(row, tier=TRAFFIC.POSITION[row["code"]][0],
                  bearing=TRAFFIC.POSITION[row["code"]][1])
             for row in rule_file["rules"]]
    market = vehicle_market(registry, rng)
    places = destinations(workplaces, pois)
    work_dest = [i for i, row in enumerate(places) if row["kind"] == "work"]
    visit_dest = [i for i, row in enumerate(places) if row["kind"] != "work"]
    delivery_dest = [i for i, row in enumerate(places)
                     if row["kind"] in ("work", "retail", "services")]

    people = len(population["person_records"])
    counts = {
        "worker": round(people * 0.018),
        "delivery": round(people * 0.003),
        "repeat_visitor": round(people * 0.010),
    }
    used = set()
    rows = []
    for kind in ("worker", "delivery", "repeat_visitor"):
        pool = work_dest if kind == "worker" else delivery_dest if kind == "delivery" else visit_dest
        weights = [places[index]["weight"] for index in pool]
        for _ in range(counts[kind]):
            destination = rng.choices(pool, weights=weights, k=1)[0]
            rows.append(make_vehicle(len(rows), kind, destination, market, rules, used, rng))

    city = city_profile.load()
    args.out.write_text(json.dumps({
        "version": 1, "seed": args.seed, "city": city.slug,
        "centre": list(city.extent.center), "radius_m": city.extent.radius_m,
        "source": {
            "traffic": "modelled fallback; replace rates with directional count intake",
            "vehicle_market": VEHICLES.name,
            "plates": "representative standard passenger serial rules",
        },
        "rates": {
            "weekday": {"through": round(people * 0.28), "single_visit": round(people * 0.055)},
            "weekend": {"through": round(people * 0.24), "single_visit": round(people * 0.075)},
            "overnight_share": 0.035,
        },
        "plate_rules": rules, "visitor_weights": TRAFFIC.ONE_OFF_WEIGHTS,
        "market": market,
        "destinations": places, "vehicles": rows,
    }, separators=(",", ":")))

    print(f"external_traffic.json ({args.out.stat().st_size / 1e6:.1f} MB)")
    print(f"{len(rows):,} recurring external vehicles: " + ", ".join(
        f"{kind} {count:,}" for kind, count in counts.items()))
    print(f"{len(places):,} shared destinations, {len(market):,} vehicle-market specimens")
    print("states: " + ", ".join(
        f"{state} {count:,}" for state, count in Counter(r["state"] for r in rows).most_common(10)))
    print(f"one-off weekday target: {round(people * 0.28):,} through, "
          f"{round(people * 0.055):,} stopping visits")


if __name__ == "__main__":
    main()
