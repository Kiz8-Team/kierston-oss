import { economy, dayFromTimeline, shared, products, transport, type DayContext } from "../../../kierston/sim/src/index.ts";
import { Baseline, type RecordedDay, positionAt } from "../replay/baseline.ts";
import { resolveTime, type Realized } from "../replay/movement.ts";
import type { Purchase, Window } from "../authoring/dsl.ts";

export async function settleActor(
  context: DayContext, baseline: Baseline, person: number, recorded: RecordedDay, windows: readonly Window[],
  purchases: readonly Purchase[], realized: Map<string, Realized>, date: Date,
  /** The minute the person died: no card is presented and no basket sampled from then on. */
  deadFrom?: number,
): Promise<economy.Posted[]> {
  const bank = context.bank;
  if (!bank || !baseline.file.header.counts.banked) throw new Error("scenario spending requires a banked base day");
  const [p, tx] = await Promise.all([baseline.file.table("person"), baseline.file.table("tx")]);
  const row = baseline.people.get(person)!;
  const queue: { at: number; old?: economy.Posted; charge?: economy.Charge; action?: Purchase }[] = [];
  const text = (field: string, i: number) => baseline.file.string(tx[field]![i]!);
  const enumAt = (group: string, field: string, i: number) => baseline.file.header.enums[group]?.[tx[field]![i]!];
  for (let i = p.txOffset![row]!; i < p.txOffset![row]! + p.txCount![row]!; i++) {
    const at = tx.minute![i]!;
    const venue = text("venue", i);
    const kind = enumAt("txKind", "kind", i) as economy.Posted["kind"];
    const reason = enumAt("reason", "reason", i) as economy.Posted["reason"];
    const lat = tx.latE6![i]!, lon = tx.lonE6![i]!;
    const located = lat !== products.NONE_I32 && lon !== products.NONE_I32;
    // A cash machine visit has no venue but a place: it happened where the
    // base day had the person, so it goes with the rest of that presence.
    const cash = kind === "withdrawal" && located;
    const physical = cash || venue !== null || ["fare", "transit", "parking", "fuel"].includes(reason);
    if ((kind === "payment" || cash) && physical && windows.some((window) => window.start <= at && at < window.end)) continue;
    if ((kind === "payment" || cash) && deadFrom !== undefined && at >= deadFrom) continue;
    queue.push({ at, old: {
      person, kind, reason, _timestamp: at, amount: Math.round(tx.amount![i]! * 100) / 100,
      approved: Boolean(tx.approved![i]), balanceAfter: null, merchant: text("merchant", i) ?? undefined,
      instrument: enumAt("instrument", "instrument", i) as economy.Instrument | undefined,
      account: text("account", i), card: text("card", i), network: text("network", i), mcc: tx.mcc![i]!,
      ...(venue ? { venue } : {}),
      ...(located ? { location: { lat: lat / 1e6, lon: lon / 1e6 } } : {}),
    } });
  }
  const newEvents = recorded.day.scheduled.timeline.filter((event) =>
    event.kind === "travel" ? event.journeyId.startsWith("scenario/") : event.activityId.startsWith("scenario/"));
  const incidental = economy.chargesFor(context, context.world.persons.get(person)!, dayFromTimeline(person, newEvents), shared.dayNumber(date));
  for (const charge of incidental) {
    if (deadFrom !== undefined && charge._timestamp >= deadFrom) continue;
    // An explicit purchase replaces the visit's automatically sampled basket.
    if (purchases.some((purchase) => purchase.venue?.id === charge.venue
        && windows.some((window) => window.start <= charge._timestamp && charge._timestamp < window.end))) continue;
    queue.push({ at: charge._timestamp, charge });
  }
  for (const purchase of purchases) {
    const at = resolveTime(purchase.at, realized);
    if (at < 0 || at >= 1440) throw new Error(`${purchase.id}: purchase outside day`);
    if (purchase.channel === "in_person") {
      const location = positionAt(recorded.day.scheduled.timeline, at, recorded.home, recorded.paths);
      // Paths of scenario legs are generated by the same router used below.
      const moving = recorded.day.legs.some((leg) => leg.depart <= at && at < leg.arrive);
      if (moving || transport.haversineKm(location, purchase.venue!) > 0.08) throw new Error(`${purchase.id}: payer is not at the merchant`);
    }
    const venue = purchase.venue?.venue;
    const merchant = purchase.channel === "online" ? purchase.merchant! : { name: venue!.name || venue!.tag, mcc: venue!.mcc! };
    queue.push({ at, action: purchase, charge: {
      person, _timestamp: at, amount: purchase.amount, merchant: merchant.name, mcc: merchant.mcc,
      reason: venue?.purposes[0] ?? "retail", instrument: purchase.instrument ?? (purchase.channel === "online" ? "debit" : undefined),
      ...(purchase.channel === "in_person" ? { venue: venue!.id, location: { id: venue!.id, lat: venue!.lat, lon: venue!.lon } } : {}),
    } });
  }
  queue.sort((a, b) => a.at - b.at); // stable: original postings precede new requests at the same minute
  const output: economy.Posted[] = [];
  for (const item of queue) {
    const posted = item.old ? economy.replayPosting(bank, item.old)
      : { ...bank.doPayment(item.charge!), reason: item.charge!.reason, venue: item.charge!.venue };
    if (item.action) realized.set(item.action.id, { person, start: item.at, arrival: item.at, departure: item.at,
      approved: posted.approved, decline: posted.decline ?? null, channel: item.action.channel, transactionInPerson: output.length });
    output.push(posted);
  }
  return output;
}
