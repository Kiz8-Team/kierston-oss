export interface ScenarioDelta {
  format: "KIERSTON_DELTA";
  version: 1;
  baseHash: string;
  /** KDAY schema the byte patches apply to. Absent on legacy v11 deltas. */
  baseVersion?: number;
  date: string;
  metadata?: BytePatch;
  columns: { name: string; patch: BytePatch }[];
  opening?: BytePatch;
  closing?: BytePatch;
  /** The ClickHouse rows the scenario changes, so Fastgate applies it without
   * the base KDAY. Absent on deltas written before the section existed. */
  records?: ScenarioRecords;
}
export interface MaterializeOptions { input: string; delta: string; output: string }
export interface MaterializeResult { output: string; baseHash: string; delta: string }
const json = (value: unknown): Buffer => Buffer.from(JSON.stringify(value));
const bytes = (value: products.NumberArray): Buffer => Buffer.from(value.buffer, value.byteOffset, value.byteLength);
const MAX_MANIFEST_BYTES = 512 * 1024 * 1024;

/** Offsets and checkpoint descriptors are regenerated by the ordinary KDAY writer. */
function metadata(file: products.KdayFile): Record<string, unknown> {
  const { columns, openingState, closingState, ...header } = file.header;
  return { ...header, strings: file.strings.values };
}

/** Fastgate's view of the in-memory scenario day. Column specs carry only what
 * its extractors read: names and counts, live after in-memory edits. */
function providerSource(file: products.KdayFile): DaySource {
  const columns = file.names().map((name) => ({ name, type: "u32" as const, count: file.count(name), byteOffset: 0, byteLength: 0 }));
  return {
    meta: { magic: "KDAY", version: file.header.version, date: file.header.date, counts: file.header.counts,
      enums: file.header.enums, strings: file.strings.values, columns },
    has: (name) => file.has(name),
    column: (name) => file.column(name),
    string: (id) => id === 0xffffffff ? null : file.string(id),
    enum: (group, id) => id === 0xff ? null : (file.header.enums[group]?.[id] ?? null),
  };
}

async function openingBytes(file: products.KdayFile): Promise<Buffer> {
  return file.header.openingState ? json(await checkpointFromKday(file.path, "opening")) : Buffer.alloc(0);
}

/** Compare the in-memory result with immutable base sections. No full scenario
 * KDAY is written. Checkpoints are diffed as JSON before gzip, so a changed
 * balance does not duplicate an entire compressed city checkpoint.
 */
export async function writeDelta(
  file: products.KdayFile, output: string, opening: StateCheckpoint, closing: StateCheckpoint, baseHash: string,
): Promise<void> {
  await distinctOutput(output, [file.path]);
  const base = await products.KdayFile.open(file.path);
  try {
    const delta: ScenarioDelta = {
      format: "KIERSTON_DELTA", version: 1, baseHash, date: base.header.date,
      baseVersion: base.header.version,
      metadata: diffBytes(json(metadata(base)), json(metadata(file))), columns: [],
      opening: diffBytes(await openingBytes(base), json(opening)),
      closing: diffBytes(json(await checkpointFromKday(base.path)), json(closing)),
    };
    if (base.names().join("\0") !== file.names().join("\0")) throw new Error("scenario delta cannot change the KDAY column schema");
    // Read base columns without caching a second city-sized set of arrays.
    const source = await open(base.path, "r");
    try {
      const prefix = Buffer.alloc(8);
      if ((await source.read(prefix, 0, 8, 0)).bytesRead !== 8) throw new Error("short base KDAY");
      const origin = Math.ceil((8 + prefix.readUInt32LE(4)) / 8) * 8;
      for (const column of base.header.columns) {
        const original = Buffer.allocUnsafe(column.byteLength);
        let at = 0;
        while (at < original.length) {
          const { bytesRead } = await source.read(original, at, original.length - at, origin + column.byteOffset + at);
          if (!bytesRead) throw new Error(`short base column ${column.name}`);
          at += bytesRead;
        }
        const next = await file.column(column.name);
        if (next.constructor !== products.ARRAYS[column.type]) throw new Error(`scenario delta cannot change column type: ${column.name}`);
        const patch = diffBytes(original, bytes(next));
        if (patch) delta.columns.push({ name: column.name, patch });
      }
    } finally { await source.close(); }
    // The provider rows this scenario changes, worked out once here so an
    // apply never needs the base again. Identity is the byte-level content.
    // CITY_TIME_ZONE, else the zone init published to sim_data/city.json.
    const timeZone = world.cityTimeZone();
    const provider = await ProviderKday.open(base.path);
    try {
      delta.records = await scenarioRecords(provider, providerSource(file), baseHash, scenarioIdentity(delta), timeZone);
    } finally { await provider.close(); }
    const prefix = Buffer.alloc(8);
    prefix.write("KDIF"); prefix.writeUInt32LE(1, 4);
    const manifest = json(delta);
    if (manifest.length > MAX_MANIFEST_BYTES) throw new Error("KDIF v1 manifest exceeds 512 MiB");
    const payload = gzipSync(manifest, { level: 9 });
    await mkdir(dirname(output), { recursive: true });
    const temporary = `${output}.tmp-${randomUUID()}`;
    const target = await open(temporary, "wx");
    try {
      await target.writeFile(prefix); await target.writeFile(payload);
      await target.sync(); await target.close();
      await rename(temporary, output);
    } catch (error) {
      await target.close().catch(() => {}); await rm(temporary, { force: true }); throw error;
    }
  } finally { await base.close(); }
}

export async function readDelta(path: string): Promise<ScenarioDelta> {
  const data = Buffer.from(await Bun.file(path).arrayBuffer());
  if (data.length < 8 || data.toString("ascii", 0, 4) !== "KDIF") throw new Error("not a KDIF scenario delta");
  if (data.readUInt32LE(4) !== 1) throw new Error("unsupported scenario delta version");
  let delta: ScenarioDelta;
  try { delta = JSON.parse(gunzipSync(data.subarray(8), { maxOutputLength: MAX_MANIFEST_BYTES }).toString("utf8")); }
  catch { throw new Error("invalid or corrupt scenario delta payload"); }
  if (!delta || delta.format !== "KIERSTON_DELTA" || delta.version !== 1 || typeof delta.baseHash !== "string"
    || !/^[a-f0-9]{64}$/.test(delta.baseHash) || typeof delta.date !== "string"
    || (delta.baseVersion !== undefined && (!Number.isSafeInteger(delta.baseVersion) || delta.baseVersion < 1))
    || !Array.isArray(delta.columns)) throw new Error("invalid scenario delta manifest");
  const names = new Set<string>();
  for (const column of delta.columns) {
    if (!column || typeof column.name !== "string" || names.has(column.name) || !column.patch) throw new Error("invalid delta column manifest");
    names.add(column.name);
  }
  return delta;
}

/** Pure storage operation: requires only the exact base and delta, never city
 * assets, a scenario module, a seed, or an engine replay.
 */
export async function materializeScenario(options: MaterializeOptions): Promise<MaterializeResult> {
  await distinctOutput(options.output, [options.input, options.delta]);
  const delta = await readDelta(options.delta);
  if (await products.fileDigest(options.input) !== delta.baseHash) throw new Error("scenario delta base hash mismatch");
  const file = await products.KdayFile.open(options.input);
  try {
    const baseVersion = delta.baseVersion ?? 11;
    if (file.header.date !== delta.date || file.header.version !== baseVersion) throw new Error("scenario delta base date/version mismatch");
    const tolerated = await brokenVehicleSpans(file);
    const oldOpening = await openingBytes(file), oldClosing = json(await checkpointFromKday(file.path));
    const opening = JSON.parse((delta.opening ? applyBytes(oldOpening, delta.opening) : oldOpening).toString("utf8")) as StateCheckpoint;
    const closing = JSON.parse((delta.closing ? applyBytes(oldClosing, delta.closing) : oldClosing).toString("utf8")) as StateCheckpoint;
    const header = delta.metadata ? JSON.parse(applyBytes(json(metadata(file)), delta.metadata).toString("utf8")) : metadata(file);
    if (!header || header.magic !== "KDAY" || header.version !== baseVersion || header.date !== delta.date
      || !Array.isArray(header.strings) || !header.strings.every((value: unknown) => typeof value === "string")
      || header.strings.length < file.strings.values.length
      || file.strings.values.some((value, i) => header.strings[i] !== value)
      || ["columns", "openingState", "closingState", "__proto__", "constructor", "prototype"].some((key) => Object.hasOwn(header, key))) {
      throw new Error("invalid scenario delta metadata");
    }
    for (const value of header.strings.slice(file.strings.values.length)) file.strings.id(value);
    if (file.strings.values.length !== header.strings.length) throw new Error("duplicate appended delta strings");
    for (const key of Object.keys(metadata(file))) if (!Object.hasOwn(header, key)) delete file.header[key];
    Object.assign(file.header, header);
    for (const column of delta.columns) {
      if (!file.has(column.name)) throw new Error(`unknown delta column ${column.name}`);
      const old = await file.column(column.name);
      const restored = applyBytes(bytes(old), column.patch);
      const type = file.header.columns.find((spec) => spec.name === column.name)!.type;
      const ArrayType = products.ARRAYS[type];
      if (restored.length % ArrayType.BYTES_PER_ELEMENT) throw new Error(`unaligned delta column ${column.name}`);
      // Buffer offsets need not meet typed-array alignment requirements.
      const aligned = Uint8Array.from(restored);
      file.set(column.name, new ArrayType(aligned.buffer));
    }
    for (const checkpoint of [opening, closing]) {
      const checkpointVersion = Number(checkpoint?.version);
      const validVersion = baseVersion >= 12 ? checkpointVersion === STATE_VERSION
        : checkpointVersion === 2 || checkpointVersion === STATE_VERSION;
      if (!checkpoint || checkpoint.magic !== "KSTATE" || !validVersion
        || !Number.isSafeInteger(checkpoint.completedDays) || checkpoint.completedDays < 0
        || ![checkpoint.persons, checkpoint.bank, checkpoint.radio, checkpoint.fleet].every(Array.isArray)
        || (baseVersion >= 12 && !Array.isArray(checkpoint.vehicles))) {
        throw new Error("invalid delta checkpoint");
      }
    }
    if (opening.nextDate !== delta.date || closing.coldStart !== opening.coldStart
      || closing.completedDays !== opening.completedDays + 1
      || shared.dayNumber(shared.parseDate(closing.nextDate)) !== shared.dayNumber(shared.parseDate(delta.date)) + 1) {
      throw new Error("invalid delta checkpoint chronology");
    }
    await validateProduct(file, tolerated);
    await file.write(options.output, opening, closing);
    return { output: options.output, baseHash: delta.baseHash, delta: options.delta };
  } finally { await file.close(); }
}
